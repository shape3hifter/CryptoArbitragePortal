-- ============================================================
-- Hourly scheduler RPC
-- ============================================================

create or replace function public.invoke_hourly_arbitrage()
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  secret_key text;
begin
  select cron_secret into secret_key
  from public.hourly_arbitrage_scheduler_config
  where id = 1 and enabled = true;

  if secret_key is null or secret_key = '' then
    raise exception 'hourly_arbitrage scheduler is disabled or missing secret';
  end if;

  perform net.http_post(
    url := 'https://ckslcyemlwphmilvduzf.supabase.co/functions/v1/hourly-arbitrage-v4',
    headers := jsonb_build_object('Content-Type','application/json','x-cron-secret',secret_key),
    body := jsonb_build_object('dry_run',(select dry_run from public.hourly_arbitrage_scheduler_config where id = 1))
  );
end;
$$;

revoke execute on function public.invoke_hourly_arbitrage() from public, anon, authenticated;

